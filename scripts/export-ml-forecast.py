"""Export national model trends for the static site; no personal records are used.

Run with odin-ml's Python environment:
  ../odin-ml/.venv/bin/python scripts/export-ml-forecast.py
Monthly indices use the serving code's cube-root quarterly growth convention.
They are derived trends, not independently trained monthly predictions.
"""
from pathlib import Path
import argparse
import calendar
import hashlib
import json
import sys

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--ml-root', type=Path, default=Path('../odin-ml'))
parser.add_argument('--year', type=int, default=2027)
args = parser.parse_args()
ml_root = args.ml_root.resolve()
sys.path.insert(0, str(ml_root))
import joblib
import numpy as np
import pandas as pd
from app.services.forecast_service import _hfce_quarterly_series

root = Path(__file__).resolve().parents[1]
model_dir = ml_root / 'models/hfce_sarima_v4'
metadata = json.loads((model_dir / 'metadata.json').read_text())
evaluation = json.loads((model_dir / 'evaluation.json').read_text())
names = {'food': 'Food', 'housing_water_utilities': 'Housing & utilities',
         'education': 'Education', 'transport': 'Transport',
         'alcohol_tobacco': 'Alcohol & tobacco', 'clothing_footwear': 'Clothing & footwear',
         'communication': 'Communication', 'furnishings_household': 'Household furnishings',
         'health': 'Health', 'miscellaneous_goods_services': 'Other goods & services',
         'recreation_culture': 'Recreation & culture', 'restaurants_hotels': 'Restaurants & hotels'}
categories = {}
quarterly = {}
hashes = {}
for category, details in evaluation['categories'].items():
    path = model_dir / details['artifact']
    artifact = joblib.load(path)
    end = pd.Period(artifact['period_end'], freq='Q')
    if pd.Period(f'{args.year}Q1', freq='Q') <= end:
        raise ValueError('Choose a full year after the observed model history')
    steps = pd.Period(f'{args.year}Q4', freq='Q').ordinal - end.ordinal
    series = _hfce_quarterly_series(artifact, steps)
    values = []
    for month in range(1, 13):
        quarter = pd.Period(f'{args.year}-{month:02}', freq='M').asfreq('Q')
        previous = float(series[quarter - 1])
        current = float(series[quarter])
        # Same monthly compounding rule as _walk_forward_multiplier in odin-ml.
        values.append(previous * (current / previous) ** (((month - 1) % 3 + 1) / 3))
    if not np.isfinite(values).all() or min(values) <= 0:
        raise ValueError(f'Invalid national trend for {category}')
    categories[category] = values
    quarterly[category] = {str(q): float(series[q]) for q in pd.period_range(f'{args.year - 1}Q4', f'{args.year}Q4', freq='Q')}
    hashes[path.name] = hashlib.sha256(path.read_bytes()).hexdigest()

totals = np.sum(list(categories.values()), axis=0)
mean = float(np.mean(totals))
months = []
for i, total in enumerate(totals):
    indices = {c: round(values[i] / float(np.mean(values)) * 100, 2) for c, values in categories.items()}
    leaders = sorted(categories, key=lambda c: categories[c][i] - float(np.mean(categories[c])), reverse=True)[:2]
    months.append({'m': calendar.month_name[i + 1], 's': calendar.month_abbr[i + 1].upper(),
                   'v': float(total / mean), 'index': round(float(total / mean * 100), 2),
                   'hot': bool(total / mean >= 1.1), 'categoryIndices': indices,
                   'why': 'Category indices: ' + '; '.join(f'{names[c]} {indices[c]:.0f}' for c in leaders) + '.'})
output = {'year': args.year, 'modelVersion': metadata['model_id'],
          'psaDataVintage': metadata['psa_data_vintage'], 'modelCreatedAt': metadata['created_at'],
          'basis': 'National HFCE trend; quarterly growth compounded evenly over three months. Each index is normalized to its own 12-month average. Not a personal expense forecast.',
          'artifactSha256': hashes, 'quarterlyForecastMillionPhp': quarterly, 'months': months}
(root / 'forecast-data.js').write_text('// Generated by scripts/export-ml-forecast.py. Do not edit by hand.\nwindow.BUDGIE_FORECAST = ' + json.dumps(output, indent=2) + ';\n')
print(f'Exported {len(months)} months and {len(categories)} categories for {args.year}.')
for m in months:
    print(f"{m['s']}: {m['index']:.2f}")
